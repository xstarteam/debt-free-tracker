const PR = { ar: new Intl.PluralRules('ar'), en: new Intl.PluralRules('en') };

// Arabic counted nouns: [one, two, few (3-10), many (11-99), other (100+, 0)]
const NOUNS = {
  month: ['شهر واحد', 'شهرين', n => `${n} أشهر`, n => `${n} شهراً`, n => `${n} شهر`],
  monthShort: ['شهر', 'شهرين', n => `${n} أشهر`, n => `${n} شهراً`, n => `${n} شهر`],
  year: ['سنة', 'سنتين', n => `${n} سنوات`, n => `${n} سنة`, n => `${n} سنة`],
  payment: ['دفعة واحدة', 'دفعتين', n => `${n} دفعات`, n => `${n} دفعة`, n => `${n} دفعة`],
  debt: ['دين واحد', 'دينين', n => `${n} ديون`, n => `${n} ديناً`, n => `${n} دين`],
};
const EN_NOUNS = {
  month: ['month', 'months'], monthShort: ['month', 'months'], year: ['year', 'years'],
  payment: ['payment', 'payments'], debt: ['debt', 'debts'],
};

/** "شهرين", "5 أشهر", "11 شهراً" / "2 months". */
export function count(lang, noun, n) {
  if (lang === 'en') {
    const [one, many] = EN_NOUNS[noun];
    return `${n} ${n === 1 ? one : many}`;
  }
  const forms = NOUNS[noun];
  const idx = { one: 0, two: 1, few: 2, many: 3 }[PR.ar.select(n)] ?? 4;
  const f = forms[idx];
  return typeof f === 'function' ? f(n) : f;
}

/** 27 -> "سنتين و3 أشهر" / "2 years, 3 months". */
export function duration(lang, months) {
  const y = Math.floor(months / 12);
  const m = months % 12;
  if (lang === 'en') {
    const parts = [];
    if (y) parts.push(count('en', 'year', y));
    if (m || !y) parts.push(count('en', 'month', m));
    return parts.join(', ');
  }
  if (!y) return count('ar', 'month', m);
  if (!m) return count('ar', 'year', y);
  return `${count('ar', 'year', y)} و${count('ar', 'monthShort', m)}`;
}

