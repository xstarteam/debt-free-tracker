export const LANGS = Object.freeze(['ar', 'en']);

/** Translator for a language + terminology ('interest' | 'profit'). */
export function translator(lang, terms = 'interest') {
  const L = LANGS.includes(lang) ? lang : 'ar';
  const dict = STRINGS[L];
  const term = (TERMS[terms] || TERMS.interest)[L];
  return {
    lang: L,
    dir: L === 'ar' ? 'rtl' : 'ltr',
    s: dict,
    term,
    count: (noun, n) => count(L, noun, n),
    duration: months => duration(L, months),
  };
}
